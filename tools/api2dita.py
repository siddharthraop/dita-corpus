#!/usr/bin/env python3
"""Generate DITA reference topics from a Google API discovery document (Set D).

    python tools/api2dita.py                 # write api/ from sources/tpu-api-v2.discovery.json
    python tools/api2dita.py --check         # regenerate in memory; exit 1 if api/ is out of date

Every method becomes a reference topic (HTTP request, path and query parameters, request and
response bodies, OAuth scopes). Every schema becomes a reference topic with a property table.
Method topics link to schema topics by key (keyref="schema-Node"), so renaming a schema file
changes one keydef, not every link.

Built with lxml's E-factory, so the output is well-formed by construction, and sorted, so a
change in the spec shows up as a small, reviewable diff. CI runs --check: if Google publishes a
new revision of the discovery document and nobody regenerates, the build fails ("spec drift").
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from lxml import etree
from lxml.builder import E

sys.path.insert(0, str(Path(__file__).resolve().parent))
from corpus import ROOT  # noqa: E402

SPEC = ROOT / "sources" / "tpu-api-v2.discovery.json"
OUT = ROOT / "api"
DOCTYPE = {
    "reference": '<!DOCTYPE reference PUBLIC "-//OASIS//DTD DITA Reference//EN" "reference.dtd">',
    "concept": '<!DOCTYPE concept PUBLIC "-//OASIS//DTD DITA Concept//EN" "concept.dtd">',
    "map": '<!DOCTYPE map PUBLIC "-//OASIS//DTD DITA Map//EN" "map.dtd">',
}
BANNER = " Generated by tools/api2dita.py from sources/tpu-api-v2.discovery.json. Do not edit; edit the generator. "
INLINE = re.compile(r"`([^`]+)`|\[([^\]]+)\]\((https?://[^)\s]+)\)")


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def mixed(tag: str, text: str, **attrs) -> etree._Element:
    """Build an element whose text turns `code` into <codeph> and [label](url) into an external <xref>."""
    el = etree.Element(tag, **attrs)
    text = " ".join((text or "").split())
    pos, last = 0, None
    for m in INLINE.finditer(text):
        chunk = text[pos:m.start()]
        if last is None:
            el.text = (el.text or "") + chunk
        else:
            last.tail = (last.tail or "") + chunk
        if m.group(1) is not None:
            last = E.codeph(m.group(1))
        else:
            last = E.xref(m.group(2), href=m.group(3), scope="external", format="html")
        el.append(last)
        pos = m.end()
    rest = text[pos:]
    if last is None:
        el.text = (el.text or "") + rest
    else:
        last.tail = (last.tail or "") + rest
    return el


def first_sentence(text: str) -> str:
    text = " ".join((text or "").split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return m.group(1) if m else (text or "No description in the discovery document.")


def type_of(prop: dict) -> str:
    if "$ref" in prop:
        return prop["$ref"]
    t = prop.get("type", "any")
    if t == "array":
        return f"array of {type_of(prop.get('items', {}))}"
    if t == "object" and "additionalProperties" in prop:
        return f"map of string to {type_of(prop['additionalProperties'])}"
    return f"{t} ({prop['format']})" if prop.get("format") else t


def type_cell(prop: dict) -> etree._Element:
    entry = E.entry()
    ref = prop.get("$ref") or prop.get("items", {}).get("$ref") or prop.get("additionalProperties", {}).get("$ref")
    if ref:
        prefix = type_of(prop).replace(ref, "")
        entry.text = prefix
        entry.append(E.xref(keyref=f"schema-{ref}"))
    else:
        entry.append(E.codeph(type_of(prop)))
    return entry


def table(headers, rows, oc):
    cols = len(headers)
    return E.table(
        E.tgroup(
            *[E.colspec(colname=f"c{i+1}") for i in range(cols)],
            E.thead(E.row(*[E.entry(h) for h in headers])),
            E.tbody(*rows),
            cols=str(cols),
        ),
        outputclass=oc,
    )


def prolog(spec: dict) -> etree._Element:
    return E.prolog(
        E.author("tools/api2dita.py", type="contributor"),
        E.critdates(E.created(date="2026-10-24"), E.revised(modified=f"{spec['revision'][:4]}-{spec['revision'][4:6]}-{spec['revision'][6:]}")),
        E.metadata(E.audience(type="developer")),
        E.data(name="source", value="tpu-api-v2", href=spec.get("documentationLink", ""), format="html", scope="external"),
        E.data(name="api-revision", value=spec["revision"]),
        E.data(name="generated", value="true"),
    )


def method_topic(spec, resource_path, name, m) -> tuple[str, etree._Element]:
    tid = slug(f"{resource_path}-{name}")
    root_url = spec["rootUrl"].rstrip("/")
    body = E.refbody()
    body.append(E.section(E.title("HTTP request"),
                          E.codeblock(f"{m['httpMethod']} {root_url}/{m['path']}", outputclass="language-http"),
                          id="http-request"))
    params = m.get("parameters", {})
    for loc, title in (("path", "Path parameters"), ("query", "Query parameters")):
        names = [p for p in m.get("parameterOrder", []) if params.get(p, {}).get("location") == loc]
        names += sorted(p for p, v in params.items() if v.get("location") == loc and p not in names)
        if not names:
            continue
        rows = []
        for p in names:
            v = params[p]
            req = "Required" if v.get("required") else "Optional"
            rows.append(E.row(E.entry(E.parmname(p)), type_cell(v), E.entry(req), E.entry(mixed("p", v.get("description", "")))))
        body.append(E.section(E.title(title), table(["Name", "Type", "Required", "Description"], rows, "api-params"), id=slug(title)))
    req = m.get("request", {}).get("$ref")
    sec = E.section(E.title("Request body"), id="request-body")
    if req:
        p = E.p("The request body contains an instance of ")
        p.append(E.xref(keyref=f"schema-{req}"))
        p[-1].tail = "."
        sec.append(p)
    else:
        sec.append(E.p("The request body must be empty."))
    body.append(sec)
    resp = m.get("response", {}).get("$ref")
    sec = E.section(E.title("Response body"), id="response-body")
    if resp:
        p = E.p("If successful, the response body contains an instance of ")
        p.append(E.xref(keyref=f"schema-{resp}"))
        p[-1].tail = "."
        sec.append(p)
    body.append(sec)
    scopes = m.get("scopes", [])
    if scopes:
        body.append(E.section(E.title("Authorization scopes"), E.ul(*[E.li(E.codeph(s)) for s in scopes]), id="scopes"))
    topic = E.reference(
        E.title(E.apiname(f"{resource_path.split('.')[-1]}.{name}")),
        mixed("shortdesc", first_sentence(m.get("description", ""))),
        prolog(spec),
        body,
        id=tid,
        **{"{http://www.w3.org/XML/1998/namespace}lang": "en-US"},
    )
    return tid, topic


def schema_topic(spec, name, s) -> tuple[str, etree._Element]:
    tid = slug(f"schema-{name}")
    rows = []
    for pname in sorted(s.get("properties", {})):
        p = s["properties"][pname]
        desc = p.get("description", "")
        if p.get("readOnly"):
            desc = "Output only. " + desc
        cell = E.entry(mixed("p", desc))
        if p.get("enum"):
            dl = E.dl()
            for val, d in zip(p["enum"], p.get("enumDescriptions", [""] * len(p["enum"]))):
                dl.append(E.dlentry(E.dt(E.codeph(val)), mixed("dd", d or "No description.")))
            cell.append(dl)
        rows.append(E.row(E.entry(E.parmname(pname)), type_cell(p), cell))
    body = E.refbody()
    if rows:
        body.append(E.section(E.title("Fields"), table(["Field", "Type", "Description"], rows, "api-schema"), id="fields"))
    else:
        body.append(E.section(E.p("This message has no fields."), id="fields"))
    topic = E.reference(
        E.title(E.apiname(name)),
        mixed("shortdesc", first_sentence(s.get("description", f"The {name} message."))),
        prolog(spec),
        body,
        id=tid,
        **{"{http://www.w3.org/XML/1998/namespace}lang": "en-US"},
    )
    return tid, topic


def walk(resources, prefix=""):
    for rname in sorted(resources):
        r = resources[rname]
        path = f"{prefix}{rname}"
        for mname in sorted(r.get("methods", {})):
            yield path, mname, r["methods"][mname]
        yield from walk(r.get("resources", {}), path + ".")


def serialize(el, kind) -> bytes:
    tree = etree.ElementTree(el)
    el.addprevious(etree.Comment(BANNER))
    return etree.tostring(tree, xml_declaration=True, encoding="UTF-8", doctype=DOCTYPE[kind], pretty_print=True)


def generate(spec: dict) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    by_resource: dict[str, list[str]] = {}
    for rpath, mname, m in walk(spec.get("resources", {})):
        tid, topic = method_topic(spec, rpath, mname, m)
        files[f"topics/methods/{tid}.dita"] = serialize(topic, "reference")
        by_resource.setdefault(rpath, []).append(tid)
    schema_ids = {}
    for sname in sorted(spec.get("schemas", {})):
        tid, topic = schema_topic(spec, sname, spec["schemas"][sname])
        files[f"topics/schemas/{tid}.dita"] = serialize(topic, "reference")
        schema_ids[sname] = tid

    scopes = spec.get("auth", {}).get("oauth2", {}).get("scopes", {})
    overview = E.concept(
        E.title(E.keyword(keyref="api-name"), " ", E.keyword(keyref="api-version")),
        mixed("shortdesc", first_sentence(spec.get("description", ""))),
        prolog(spec),
        E.conbody(
            E.p("Service endpoint: ", E.codeph(E.keyword(keyref="api-root-url"))),
            E.p("Discovery revision: ", E.keyword(keyref="api-revision"), "."),
            E.note("Every topic in this set is generated from the discovery document. To change a description, fix it "
                   "upstream or in the generator, then run tools/api2dita.py.", type="note"),
            E.section(E.title("OAuth scopes"), E.ul(*[E.li(E.codeph(s), " ", mixed("ph", d.get("description", ""))) for s, d in sorted(scopes.items())]), id="scopes"),
        ),
        id="api-overview",
        **{"{http://www.w3.org/XML/1998/namespace}lang": "en-US"},
    )
    files["topics/api-overview.dita"] = serialize(overview, "concept")

    keys = E.map(E.title("Cloud TPU API key definitions"), id="api-keys")
    for k, v in (("api-name", spec.get("title", spec["name"])), ("api-version", spec["version"]),
                 ("api-revision", spec["revision"]), ("api-root-url", spec["rootUrl"])):
        keys.append(E.keydef(E.topicmeta(E.keywords(E.keyword(v))), keys=k))
    for sname, tid in schema_ids.items():
        keys.append(E.keydef(keys=f"schema-{sname}", href=f"../topics/schemas/{tid}.dita"))
    files["keys/api-keys.ditamap"] = serialize(keys, "map")

    m = E.map(E.title(E.keyword(keyref="api-name"), " reference (generated)"), id="tpu-api")
    m.append(E.mapref(href="keys/api-keys.ditamap", **{"processing-role": "resource-only"}))
    m.append(E.topicref(href="topics/api-overview.dita"))
    methods = E.topichead(E.topicmeta(E.navtitle("Methods")))
    for rpath in sorted(by_resource):
        head = E.topichead(E.topicmeta(E.navtitle(rpath)))
        for tid in by_resource[rpath]:
            head.append(E.topicref(href=f"topics/methods/{tid}.dita"))
        methods.append(head)
    m.append(methods)
    schemas = E.topichead(E.topicmeta(E.navtitle("Types")))
    for sname, tid in schema_ids.items():
        schemas.append(E.topicref(href=f"topics/schemas/{tid}.dita"))
    m.append(schemas)
    files["tpu-api.ditamap"] = serialize(m, "map")
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if api/ differs from a fresh generation")
    ap.add_argument("--spec", type=Path, default=SPEC)
    args = ap.parse_args()
    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    files = generate(spec)
    if args.check:
        drift = [p for p, data in files.items() if not (OUT / p).exists() or (OUT / p).read_bytes() != data]
        stale = [str(p.relative_to(OUT)) for p in OUT.rglob("*.dita*") if str(p.relative_to(OUT)) not in files]
        if drift or stale:
            print(f"API reference is out of date: {len(drift)} changed, {len(stale)} removed. Run tools/api2dita.py.")
            for p in (drift + stale)[:20]:
                print("  ", p)
            return 1
        print(f"API reference is current: {len(files)} files match revision {spec['revision']}.")
        return 0
    for p in OUT.rglob("*.dita*"):
        if str(p.relative_to(OUT)) not in files:
            p.unlink()
    for p, data in files.items():
        dest = OUT / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
    n_methods = sum(1 for p in files if p.startswith("topics/methods/"))
    n_schemas = sum(1 for p in files if p.startswith("topics/schemas/"))
    print(f"Wrote {len(files)} files: {n_methods} method topics, {n_schemas} schema topics, revision {spec['revision']}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
